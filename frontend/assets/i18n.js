const DEFAULT_LANG = "ru";

function currentLang() {
  return window.localStorage.getItem("geointel_lang") || DEFAULT_LANG;
}

function setLang(lang) {
  window.localStorage.setItem("geointel_lang", lang);
  applyTranslations();
}

function t(key, lang = currentLang()) {
  return DICTS[lang]?.[key] ?? DICTS[DEFAULT_LANG][key] ?? key;
}

function applyTranslations() {
  const lang = currentLang();
  document.documentElement.setAttribute("lang", lang === "ky" ? "ky" : lang === "en" ? "en" : "ru");
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"), lang);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder"), lang));
  });
}

window.GeoIntelI18n = { t, setLang, currentLang, applyTranslations };
document.addEventListener("DOMContentLoaded", applyTranslations);
